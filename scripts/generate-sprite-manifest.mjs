// Emits src/game/phaser/spriteAssets.ts — a manifest of require() calls for every knight/sword PNG.
//
// Metro has to SEE a literal require() per asset to bundle it and hand back a resolvable URI, so the
// paths can't be built at runtime from the metadata.json. There are ~150 of them (8 directions x 9
// frames x 2 animations, plus idle rotations and the sword), hence generating the file instead of
// hand-writing it. Re-run with `npm run generate:sprites` whenever the art in assets/Character
// changes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const KNIGHT = 'assets/Character/Chevalier/un_chevalier_de_jeu_video';
const SWORD = 'assets/Character/Chevalier/je_veux_une_epee_qui_colle_ave';
const RUN_ANIM = 'The_character_leans_forward_into_a_steady_rhythmic';
const DASH_ANIM = 'Le_personnage_se_propulse_violemment_vers_l_avant';
const OUT = path.join(ROOT, 'src/game/phaser/spriteAssets.ts');

// Order matters: it's the 8-way lookup used by directionFor() in mainScene.ts, walking angles from
// atan2(dy, dx) in PI/4 steps. Screen y grows downward, so a growing angle goes east -> south-east
// -> south, not east -> north-east.
const DIRECTIONS = ['east', 'south-east', 'south', 'south-west', 'west', 'north-west', 'north', 'north-east'];

/** Path relative to the generated file, in the forward-slash form require() expects. */
function rel(assetPath) {
  return path.relative(path.dirname(OUT), path.join(ROOT, assetPath)).split(path.sep).join('/');
}

function requireLine(assetPath) {
  const full = path.join(ROOT, assetPath);
  if (!fs.existsSync(full)) throw new Error(`Missing asset: ${assetPath}`);
  return `require('${rel(assetPath)}')`;
}

function rotations(folder) {
  return DIRECTIONS.map((dir) => `  '${dir}': ${requireLine(`${folder}/rotations/${dir}.png`)},`).join('\n');
}

function animation(folder, anim) {
  return DIRECTIONS.map((dir) => {
    const dirPath = path.join(ROOT, folder, 'animations', anim, dir);
    const frames = fs
      .readdirSync(dirPath)
      .filter((f) => f.endsWith('.png'))
      .sort();
    const list = frames.map((f) => `    ${requireLine(`${folder}/animations/${anim}/${dir}/${f}`)},`).join('\n');
    return `  '${dir}': [\n${list}\n  ],`;
  }).join('\n');
}

const out = `// AUTO-GENERATED by scripts/generate-sprite-manifest.mjs — do not edit by hand.
/* eslint-disable @typescript-eslint/no-require-imports */

export type Direction8 =
  | 'east'
  | 'north-east'
  | 'north'
  | 'north-west'
  | 'west'
  | 'south-west'
  | 'south'
  | 'south-east';

/** Indexed by round(atan2(dy, dx) / (PI/4)) mod 8 — screen y grows downward, so index 1 (PI/4) is
 * south-east, not north-east. */
export const DIRECTIONS: Direction8[] = [
${DIRECTIONS.map((d) => `  '${d}',`).join('\n')}
];

export const KNIGHT_IDLE: Record<Direction8, number> = {
${rotations(KNIGHT + '/Idle')}
};

export const KNIGHT_RUN: Record<Direction8, number[]> = {
${animation(KNIGHT + '/mid_run', RUN_ANIM)}
};

export const KNIGHT_DASH: Record<Direction8, number[]> = {
${animation(KNIGHT + '/mid_very_fast_dash', DASH_ANIM)}
};

/** The plain sword. The magic-imbued variant (l_epee_est_impregner) is deliberately left out for now. */
export const SWORD_SPRITE: number = ${requireLine(SWORD + '/je_veux_une_epee_qui_colle_ave/rotations/je_veux_une_epee_qui_colle_ave.png')};
`;

fs.writeFileSync(OUT, out);
const count = (out.match(/require\(/g) || []).length;
console.log(`Wrote ${path.relative(ROOT, OUT)} (${count} assets)`);
